"use strict";

/*
 * Builds the single-file distribution bundle for the Session Replay plugin.
 *
 * The bundle is just the pinned rrweb UMD build (which sets `window.rrweb`)
 * followed by our integration source (which reads `window.rrweb`). No webpack
 * needed — plain concatenation, mirroring how plugin/boomerang ships a vendored
 * library alongside the Countly integration.
 *
 *   node plugin/session-replay/build.js
 *
 * Produces: plugin/session-replay/countly_session_replay.min.js
 */

var fs = require("fs");
var path = require("path");

var dir = __dirname;
var rrweb = fs.readFileSync(path.join(dir, "rrweb.min.js"), "utf8");
var integration = fs.readFileSync(path.join(dir, "countly_session_replay.js"), "utf8");

var banner = "/* Countly Session Replay bundle — rrweb (vendored) + Countly integration. Generated by build.js; do not edit directly. */\n";
var out = banner + rrweb + "\n;\n" + integration;

var target = path.join(dir, "countly_session_replay.min.js");
fs.writeFileSync(target, out, "utf8");

// eslint-disable-next-line no-console
console.log("Wrote " + target + " (" + out.length + " bytes)");
